"""Make video/god-cine.js: a copy of web/god.js that a script can drive frame by frame (for the submission video).

The god's form, shaders and data mapping stay exactly those of web/god.js; only the driving changes:
  - no animation loop of its own: `handle.renderAt(t)` draws the frame for scene time t (seconds), so a render is
    smooth and repeatable whatever the machine's speed;
  - `handle.setCamera({pos, look, fov})` replaces the worshipper's camera (null gives it back);
  - `handle.setStare(true)` turns every eye toward the camera;
  - the drawing buffer is preserved so each frame can be read back.
Run it again after web/god.js changes:  python3 video/make_god_copy.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, DST = ROOT / "web" / "god.js", ROOT / "video" / "god-cine.js"

PATCHES = [
    # the renderer keeps its last frame so the page can read it back
    ('const renderer = new THREE.WebGLRenderer({ canvas, antialias: false, powerPreference: "high-performance" });',
     'const renderer = new THREE.WebGLRenderer({ canvas, antialias: false, powerPreference: "high-performance", preserveDrawingBuffer: true });'),
    # never start a real-time loop: frames are drawn only by renderAt()
    ("let lastT = 0, running = !document.hidden, alive = true, fps = 0;",
     "let lastT = 0, running = false, alive = true, fps = 0, camOverride = null, stareAll = false;"),
    ("const resume = () => { const was = running;",
     "const resume = () => { return; const was = running;"),
    ("  requestAnimationFrame(tick);\n\n  // ---------------------------------------------------------------- picking",
     "\n  // ---------------------------------------------------------------- picking"),
    # the camera comes from the video script when it is set
    ("placeCamera(time, px, py); U.uTime.value = time;",
     "if (camOverride) { camera.position.copy(camOverride.pos); camera.lookAt(camOverride.look);"
     " if (camOverride.fov && camera.fov !== camOverride.fov) { camera.fov = camOverride.fov; camera.updateProjectionMatrix(); } }"
     " else placeCamera(time, px, py); U.uTime.value = time;"),
    # every eye can be made to look at the camera
    ('if (e.kind === "blind") target = tv.copy(camP);',
     'if (e.kind === "blind" || (stareAll && e.kind !== "great")) target = tv.copy(camP);'),
    ("const drift = CALM ? 0.4 : 1, follow = now - pointerAt < 5000;",
     "const drift = CALM ? 0.4 : 1, follow = stareAll || now - pointerAt < 5000;"),
    # the handle
    ("    setFocus(tx) { focusTx = tx || null; },",
     "    setFocus(tx) { focusTx = tx || null; },\n"
     "    setCamera(o) { camOverride = o || null; },\n"
     "    setStare(v) { stareAll = !!v; },\n"
     "    renderAt(t) { tick(T0 + t * 1000, true); },\n"
     "    eyes() { return eyeList.map((e, i) => ({ kind: e.kind, tx: e.tx || (e.it ? e.it.tx : null), r: e.r, pos: eyePos[i].clone() })); },"),
    ('window.God = { supported, mount, genes };\nwindow.dispatchEvent(new Event("god-ready"));',
     'window.GodCine = { supported, mount, genes };\nwindow.dispatchEvent(new Event("god-cine-ready"));'),
]

HEADER = ("// GENERATED by video/make_god_copy.py from web/god.js for the submission video: driven frame by frame,\n"
          "// camera set by video/cine.js. Do not edit; edit web/god.js or the patch list and regenerate.\n")


def main() -> None:
    s = SRC.read_text(encoding="utf-8")
    for old, new in PATCHES:
        n = s.count(old)
        if n != 1:
            raise SystemExit(f"patch target found {n} times (want 1): {old[:70]!r}")
        s = s.replace(old, new)
    s = s.replace('from "./vendor/three/BufferGeometryUtils.js"', 'from "../web/vendor/three/BufferGeometryUtils.js"')
    DST.write_text(HEADER + s, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)} ({len(s)} chars)")


if __name__ == "__main__":
    main()
